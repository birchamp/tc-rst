//! Generates `i18n::keys`: one constant for each key of the English catalogs, so a misspelled
//! key in a view does not compile (APP-DESIGN §6.9).
//!
//! The keys are the union of `assets/i18n/en.json` (tC4's) and `assets/i18n-rebuild/en.json`
//! (the rebuild's own). A key becomes a path of nested modules, because flat names collide in
//! tC4's real catalog: `upgrade.text.gateway` and `upgrade.textGateway` would both be
//! `UPGRADE_TEXT_GATEWAY`. Each dotted segment but the last is a module in snake case
//! (`syncResult` is `sync_result`); the last is a constant in screaming snake case
//! (`lock-held` is `LOCK_HELD`). The build fails, naming the key, when a key is in both files,
//! is not a dotted path of plain segments, or gives the same Rust path as another key.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

type Error = Box<dyn std::error::Error>;

/// Words Rust reserves. A module named like one is written `r#word`; the four that cannot be
/// raw identifiers stop the build instead.
const KEYWORDS: &[&str] = &[
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "do", "dyn",
    "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in", "let",
    "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref", "return",
    "static", "struct", "trait", "true", "try", "type", "typeof", "unsafe", "unsized", "use",
    "virtual", "where", "while", "yield",
];
const NOT_RAW: &[&str] = &["crate", "self", "super", "Self"];

fn main() -> Result<(), Error> {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let out = PathBuf::from(std::env::var("OUT_DIR")?);
    let vendored = manifest.join("assets/i18n/en.json");
    let rebuild = manifest.join("assets/i18n-rebuild/en.json");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", vendored.display());
    println!("cargo:rerun-if-changed={}", rebuild.display());

    let mut messages = BTreeMap::new();
    for path in [&vendored, &rebuild] {
        for (key, text) in read_catalog(path)? {
            if messages.insert(key.clone(), text).is_some() {
                return Err(format!(
                    "the key {key} is in both English catalogs; the rebuild's file never repeats a key of tC4's"
                )
                .into());
            }
        }
    }

    let mut root = Module::default();
    for (key, text) in &messages {
        root.insert(key, text)?;
    }

    let mut code = String::from(
        "// Generated by build.rs from assets/i18n/en.json and assets/i18n-rebuild/en.json.\n\n",
    );
    root.write(&mut code, 0)?;
    code.push_str("\n/// Every key, in key order.\npub const ALL: &[crate::i18n::Key] = &[\n");
    for key in messages.keys() {
        writeln!(code, "    crate::i18n::Key({key:?}),")?;
    }
    code.push_str("];\n");
    std::fs::write(out.join("i18n_keys.rs"), code)?;
    Ok(())
}

/// The string entries of a flat JSON catalog.
fn read_catalog(path: &Path) -> Result<Vec<(String, String)>, Error> {
    let text = std::fs::read_to_string(path)
        .map_err(|e| format!("cannot read {}: {e}", path.display()))?;
    let serde_json::Value::Object(map) =
        serde_json::from_str(&text).map_err(|e| format!("{} is not JSON: {e}", path.display()))?
    else {
        return Err(format!("{} is not a JSON object", path.display()).into());
    };
    let mut entries = Vec::with_capacity(map.len());
    for (key, value) in map {
        let serde_json::Value::String(message) = value else {
            return Err(format!("{}: the entry {key} is not a string", path.display()).into());
        };
        entries.push((key, message));
    }
    Ok(entries)
}

#[derive(Default)]
struct Module {
    /// Snake-case name -> the segment it came from and its contents.
    modules: BTreeMap<String, (String, Module)>,
    /// Screaming-snake name -> the full key and its English text.
    constants: BTreeMap<String, (String, String)>,
}

impl Module {
    fn insert(&mut self, key: &str, text: &str) -> Result<(), Error> {
        let segments: Vec<&str> = key.split('.').collect();
        let valid = segments.len() >= 2
            && segments.iter().all(|s| {
                s.starts_with(|c: char| c.is_ascii_alphabetic())
                    && s.chars()
                        .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
            });
        if !valid {
            return Err(format!(
                "the key {key} is not a dotted path: two or more segments of ASCII letters, digits, - and _ that start with a letter"
            )
            .into());
        }
        let Some((last, parents)) = segments.split_last() else {
            return Err(format!("the key {key} is empty").into());
        };
        let mut module = self;
        for segment in parents {
            let name = snake(segment);
            let (origin, next) = module
                .modules
                .entry(name.clone())
                .or_insert_with(|| ((*segment).to_owned(), Module::default()));
            if origin.as_str() != *segment {
                return Err(format!(
                    "the key {key}: the segments {origin} and {segment} are both the module {name}"
                )
                .into());
            }
            module = next;
        }
        let name = snake(last).to_ascii_uppercase();
        if let Some((other, _)) = module
            .constants
            .insert(name.clone(), (key.to_owned(), text.to_owned()))
        {
            return Err(format!("the keys {other} and {key} are both the constant {name}").into());
        }
        Ok(())
    }

    fn write(&self, code: &mut String, depth: usize) -> Result<(), Error> {
        let pad = "    ".repeat(depth);
        for (name, (key, text)) in &self.constants {
            writeln!(code, "{pad}#[doc = {text:?}]")?;
            writeln!(
                code,
                "{pad}pub const {name}: crate::i18n::Key = crate::i18n::Key({key:?});"
            )?;
        }
        for (name, (_, module)) in &self.modules {
            if NOT_RAW.contains(&name.as_str()) {
                return Err(format!("a key has the segment {name}, which Rust cannot name").into());
            }
            let ident = if KEYWORDS.contains(&name.as_str()) {
                format!("r#{name}")
            } else {
                name.clone()
            };
            writeln!(code, "{pad}pub mod {ident} {{")?;
            module.write(code, depth + 1)?;
            writeln!(code, "{pad}}}")?;
        }
        Ok(())
    }
}

/// A segment in snake case: words split at `-` and `_` and where a lower-case letter or a
/// digit meets a capital (`syncResult` is `sync_result`, `lock-held` is `lock_held`).
fn snake(segment: &str) -> String {
    let mut words: Vec<String> = Vec::new();
    let mut word = String::new();
    let mut previous: Option<char> = None;
    for c in segment.chars() {
        if c == '-' || c == '_' {
            if !word.is_empty() {
                words.push(std::mem::take(&mut word));
            }
            previous = None;
            continue;
        }
        let capital_after_lower = c.is_ascii_uppercase()
            && previous.is_some_and(|p| p.is_ascii_lowercase() || p.is_ascii_digit());
        if capital_after_lower && !word.is_empty() {
            words.push(std::mem::take(&mut word));
        }
        word.push(c.to_ascii_lowercase());
        previous = Some(c);
    }
    if !word.is_empty() {
        words.push(word);
    }
    words.join("_")
}
