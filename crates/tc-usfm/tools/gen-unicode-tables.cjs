// Generates src/words/tables.rs: the character classes that tC4's word tokenizer
// (string-punctuation-tokenizer 2.0.0 on xregexp 4.4.1) uses, so the Rust tokenizer
// splits words exactly as tC4 does.
//
// Run from the crate directory, with the pinned packages installed somewhere:
//   npm install --ignore-scripts xregexp@4.4.1
//   node tools/gen-unicode-tables.cjs <path to node_modules> > src/words/tables.rs
//
// xregexp 4.4.1 without the astral flag matches `\p{..}` against BMP code points only,
// so the tables stop at U+FFFF and every astral character is classified as "other".
const path = require("path");
const nm = process.argv[2];
if (!nm) throw new Error("usage: gen-unicode-tables.cjs <node_modules>");
const XRegExp = require(path.join(nm, "xregexp"));
const version = require(path.join(nm, "xregexp", "package.json")).version;
if (version !== "4.4.1") throw new Error(`expected xregexp 4.4.1, found ${version}`);

// The exact classes from string-punctuation-tokenizer 2.0.0 src/tokenizers.js.
const classes = {
  WORD: XRegExp("^[\\pL\\pM\\u200D\\u2060]$"),
  NUMBER: XRegExp("^[\\pN\\pNd\\pNl\\pNo]$"),
  PUNCTUATION: XRegExp("^\\p{P}$"),
  WHITESPACE: /^\s$/,
};

const out = [];
out.push("// @generated by tools/gen-unicode-tables.cjs from xregexp 4.4.1. Do not edit.");
out.push("// Inclusive BMP code point ranges, sorted. Astral code points belong to no class.");
out.push("");
for (const [name, re] of Object.entries(classes)) {
  const ranges = [];
  let start = -1;
  for (let cp = 0; cp <= 0x10000; cp++) {
    // Surrogate code units are never a whole Rust `char`, so they are left out.
    const inClass = cp <= 0xffff && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCharCode(cp));
    if (inClass && start < 0) start = cp;
    if (!inClass && start >= 0) {
      ranges.push([start, cp - 1]);
      start = -1;
    }
  }
  out.push("#[rustfmt::skip]");
  out.push(`pub(super) const ${name}: &[(u16, u16)] = &[`);
  for (let i = 0; i < ranges.length; i += 6) {
    const row = ranges
      .slice(i, i + 6)
      .map(([a, b]) => `(0x${a.toString(16).toUpperCase().padStart(4, "0")}, 0x${b.toString(16).toUpperCase().padStart(4, "0")})`)
      .join(", ");
    out.push(`    ${row},`);
  }
  out.push("];");
  out.push("");
}
process.stdout.write(out.join("\n"));
