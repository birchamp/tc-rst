// Generates src/derivations/usfmjs_tables.rs: the marker table of usfm-js 3.4.3 (lib/js/USFM.js),
// which decides how its parser treats each marker and therefore what `plain_text_v1` and
// `selections_v1` return.
//
// Run from the crate directory, with tC4's pinned packages installed somewhere (tC4's own
// node_modules works):
//   node tools/gen-usfmjs-tables.cjs <path to node_modules> > src/derivations/usfmjs_tables.rs
const path = require("path");
const nm = process.argv[2];
if (!nm) throw new Error("usage: gen-usfmjs-tables.cjs <node_modules>");
const version = require(path.join(nm, "usfm-js", "package.json")).version;
if (version !== "3.4.3") throw new Error(`expected usfm-js 3.4.3, found ${version}`);
const USFM = require(path.join(nm, "usfm-js", "lib", "js", "USFM.js"));

const known = new Set(["type", "endTag", "display", "attrib", "endAttrib", "milestone", "standalone", "usfm3Milestone"]);
const str = (s) => JSON.stringify(s);
const out = [];
out.push("// @generated by tools/gen-usfmjs-tables.cjs from usfm-js 3.4.3 (lib/js/USFM.js). Do not edit.");
out.push("");
out.push("use super::usfmjs::{EndTag, Props};");
out.push("");
out.push("/// `USFM_PROPERTIES`, sorted by marker name.");
out.push("#[rustfmt::skip]");
out.push("pub(super) const PROPERTIES: &[(&str, Props)] = &[");
for (const tag of Object.keys(USFM.USFM_PROPERTIES).sort()) {
  const p = USFM.USFM_PROPERTIES[tag];
  for (const k of Object.keys(p)) if (!known.has(k)) throw new Error(`unknown property ${k} on ${tag}`);
  let endTag = "EndTag::None";
  if (Array.isArray(p.endTag)) endTag = `EndTag::Many(&[${p.endTag.map(str).join(", ")}])`;
  else if (typeof p.endTag === "string") endTag = `EndTag::One(${str(p.endTag)})`;
  else if (p.endTag !== undefined) throw new Error(`endTag of ${tag}`);
  const flag = (k) => {
    if (p[k] !== undefined && typeof p[k] !== "boolean") throw new Error(`${k} of ${tag}`);
    return p[k] === true;
  };
  out.push(
    `    (${str(tag)}, Props { ty: ${p.type === undefined ? "None" : `Some(${str(p.type)})`}, end_tag: ${endTag}, ` +
      `display: ${flag("display")}, attrib: ${flag("attrib")}, end_attrib: ${flag("endAttrib")}, ` +
      `standalone: ${flag("standalone")}, usfm3_milestone: ${flag("usfm3Milestone")} }),`,
  );
}
out.push("];");
out.push("");
out.push("/// `SPECIAL_END_TAGS`: an end marker and the start marker it closes, sorted.");
out.push("#[rustfmt::skip]");
out.push("pub(super) const SPECIAL_END_TAGS: &[(&str, &str)] = &[");
for (const tag of Object.keys(USFM.SPECIAL_END_TAGS).sort()) out.push(`    (${str(tag)}, ${str(USFM.SPECIAL_END_TAGS[tag])}),`);
out.push("];");
out.push("");
out.push("/// `MARKERS_WITH_NUMBERS`, sorted.");
out.push(`pub(super) const MARKERS_WITH_NUMBERS: &[&str] = &[${Object.keys(USFM.MARKERS_WITH_NUMBERS).sort().map(str).join(", ")}];`);
out.push("");
out.push("/// `wordSpecialAttributes`: the `x-` attributes of `\\w` whose prefix is dropped.");
out.push(`pub(super) const WORD_SPECIAL_ATTRIBUTES: &[&str] = &[${USFM.wordSpecialAttributes.map(str).join(", ")}];`);
process.stdout.write(out.join("\n") + "\n");
