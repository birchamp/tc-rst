"""Write .audit/STATUS.md: which units are on main, which remain, which can start now, and the
arguments to restart the runs. Run it in the repository: python3 -I .audit/tools/status.py [ref].

Done units come from the merge commits on main (and a fixed list of units merged before this
script existed), so the file is right even when nobody updated it by hand.
"""
import os, re, subprocess, sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
REF = sys.argv[1] if len(sys.argv) > 1 else "origin/claude/focused-ride-5uzj7p"

def git(*a):
    return subprocess.run(["git", "-C", REPO, *a], capture_output=True, text=True, check=True).stdout

# Units merged before merge subjects named them consistently.
BASE_DONE = {"J1", "J2", "C", "S1", "A1", "A2", "A3", "A4a", "A4b", "A5", "A6a", "A6b", "A7", "A8", "A9",
             "A10", "A11", "G0", "B1a", "B1b", "B2", "C0", "C1a",
             "FIX-helps", "FIX-misc", "FIX-text", "FIX-quit", "FIX-proxy"}

def design_units():
    text = open(os.path.join(REPO, "docs/APP-DESIGN.md"), encoding="utf-8").read()
    start, end = text.index("### Phase 0: now"), text.index("**Order and parallelism.**")
    units, phase = [], None
    for line in text[start:end].splitlines():
        m = re.match(r"### Phase (\d)", line)
        if m: phase = int(m.group(1)); continue
        if not line.startswith("| ") or line.startswith(("| Unit", "|---")): continue
        cells = [c.strip() for c in line.strip().strip("|").split(" | ")]
        if len(cells) < 4: continue
        uid = cells[0].split()[0]
        name = re.sub(r"\*\(.*?\)\*", "", cells[0][len(uid):]).replace("◆", "").strip()
        deps = [d for d in re.findall(r"\b([A-GJ]\d+[a-b]?|S1|S2|C|X|I|P)\b", cells[2]) if d != uid]
        units.append({"id": uid, "name": name, "phase": phase, "deps": deps, "noloss": "◆" in cells[0]})
    return units

STORAGE = [("J1", "tc-journal model and codecs"), ("J2", "fold and conflicts"), ("C", "converge with main"),
           ("S1", "tc-store: store I/O, open, saves"), ("S2", "materialize, Git, outside edits (state-machine redesign)"),
           ("P", "scale against the reference laptop"), ("T", "storage side of the tC4 issue sweep"),
           ("X", "Door43 sync and USB exchange"), ("I", "tC4 and tC3 import"), ("V", "CI gate that keeps old projects working")]
FIXES = [("FIX-helps", "tC4 #773, #661"), ("FIX-misc", "tC4 #701, #552, #549"), ("FIX-text", "tC4 #782, #795, #796"),
         ("FIX-align", "tC4 #787, #789, #790, #793, #794, #796"), ("FIX-quit", "quit race in tc-server"),
         ("FIX-proxy", "hazard 6: PAC and WPAD on Windows")]

def main():
    sha = git("rev-parse", "--short", REF).strip()
    when = git("log", "-1", "--format=%cI", REF).strip()
    subjects = git("log", "--merges", "--format=%s", REF).splitlines()
    done = set(BASE_DONE)
    ids = {u["id"] for u in design_units()} | {k for k, _ in STORAGE} | {k for k, _ in FIXES}
    for s in subjects:
        m = re.match(r"Merge ([A-Za-z0-9-]+)[:\s]", s)
        if m and m.group(1) in ids: done.add(m.group(1))
        m = re.match(r"Merge storage: unit (\w+)", s)
        if m: done.add(m.group(1))
    units = design_units()
    out = [f"# Status (generated)", "",
           f"Generated by `.audit/tools/status.py` from `{REF}` at {sha} ({when}). Do not edit by hand:",
           "the watcher regenerates it whenever main moves. `.audit/PROGRESS.md` is the written summary,",
           "`.audit/HANDOFF.md` says how to continue.", ""]
    total = len(units); n = sum(u["id"] in done for u in units)
    out += [f"**App layer: {n} of {total} units on main.** Storage: {sum(k in done for k, _ in STORAGE)} of {len(STORAGE)}. "
            f"Fixes from the tC4 sweep: {sum(k in done for k, _ in FIXES)} of {len(FIXES)}.", ""]
    out += ["## Storage (`docs/STORAGE.md`)", "", "| Unit | What | State |", "|---|---|---|"]
    out += [f"| {k} | {w} | {'done' if k in done else 'to do'} |" for k, w in STORAGE]
    out += ["", "## App layer (`docs/APP-DESIGN.md` §10)", "",
            "| Unit | What | Phase | State | Waits for |", "|---|---|---|---|---|"]
    for u in units:
        if u["id"] in done:
            state, waits = "done", ""
        else:
            unmet = [d for d in u["deps"] if d not in done]
            state = "ready to start" if not unmet else "to do"
            waits = ", ".join(unmet)
        out.append(f"| {u['id']}{' ◆' if u['noloss'] else ''} | {u['name']} | {u['phase']} | {state} | {waits} |")
    out += ["", "◆ marks no-loss units: three verification lenses and a model-based property test.", "",
            "## Fixes from the tC4 issue sweep (`docs/TC4-ISSUES.md`)", "", "| Unit | Issues | State |", "|---|---|---|"]
    out += [f"| {k} | {w} | {'done' if k in done else 'to do'} |" for k, w in FIXES]
    lane_done = sorted({u["id"].lower() for u in units if u["id"] in done} | {"C", "S1"} & done | ({"S2"} & done) | ({"X"} & done) | ({"I"} & done) | ({"P"} & done))
    lane_done += [k for k in ("flife",) if "FIX-quit" in done]
    out += ["", "## Restarting the lane", "",
            "Units on main go into `done`; units with a branch in progress go into `cont` (see HANDOFF).", "",
            "```js", "Workflow({ scriptPath: '.audit/workflows/build-lane.js', args: {",
            "  root: '/home/bot/tc-rst', tc4: '/home/bot/unfoldingword/translationcore4',",
            f"  done: {lane_done},",
            "  skip: ['ftext', 'falign'], cont: {}, notes: {} } })", "```", ""]
    path = os.path.join(REPO, ".audit/STATUS.md")
    new = "\n".join(out)
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    strip = lambda t: re.sub(r"^Generated by .*$", "", t, flags=re.M)
    if strip(old) != strip(new):
        open(path, "w", encoding="utf-8").write(new)
        print("changed")
    else:
        print("unchanged")

main()
